// Regenerates src/data/icons.ts from lucide-static. Add a name to NAMES, then run: node scripts/build-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const NAMES = [
  'shopping-bag', 'map-pin', 'clock', 'sparkles', 'leaf', 'flame', 'plus', 'minus', 'x', 'arrow-right', 'arrow-left',
  'chevron-down', 'send', 'utensils', 'phone', 'mail', 'search', 'check', 'trash-2', 'globe', 'menu', 'sun', 'moon',
  'info', 'triangle-alert', 'message-circle', 'navigation', 'store', 'gift', 'users', 'calendar', 'chef-hat',
  'circle-check', 'circle-alert', 'loader-circle', 'shield-check', 'receipt', 'building-2', 'locate', 'star', 'cake',
  'external-link',
];

const icons = {};
for (const name of NAMES) {
  const svg = readFileSync(new URL(`../node_modules/lucide-static/icons/${name}.svg`, import.meta.url), 'utf8');
  icons[name] = svg
    .replace(/<!--[\s\S]*?-->/, '')
    .replace(/^[\s\S]*?<svg[\s\S]*?>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s*\n\s*/g, '')
    .trim();
}

writeFileSync(
  new URL('../src/data/icons.ts', import.meta.url),
  `/* Generated by scripts/build-icons.mjs from lucide-static@1.74.0 (ISC). Inner SVG markup for 24x24 stroke icons. */\n` +
    `export const ICONS = ${JSON.stringify(icons, null, 1)} as const;\nexport type IconName = keyof typeof ICONS;\n`,
);
console.log(`Wrote ${NAMES.length} icons.`);
